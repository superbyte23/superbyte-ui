    public static function render(string $name, int $size = self::SIZE, string $class = ''): string
    {
        $canonical = self::canonical($name);

        if (! isset(self::PATHS[$canonical])) {
            return '';
        }

        $classes = trim('lucide lucide-'.str_replace('_', '-', $canonical).' '.$class);

        return sprintf(
            '<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="%s" aria-hidden="true">%s</svg>',
            $size,
            $size,
            e($classes),
            self::PATHS[$canonical],
        );
    }

    public static function canonical(string $name): string
    {
        $key = strtolower(trim($name));

        return self::ALIASES[$key] ?? str_replace('_', '-', $key);
    }

    public static function has(string $name): bool
    {
        return isset(self::PATHS[self::canonical($name)]);
    }
